export function scaffoldScript({ prd }) {
  const name = prd.manifest.case;
  return [
    '#!/usr/bin/env bash',
    '# Generated by evals-public-projects/tools/generate-cases.mjs. Do not edit; regenerate.',
    '#',
    `# Scaffold for "${name}": builds the agent workspace in the current (empty)`,
    '# run directory from the frozen source bundle, verified offline, and puts',
    "# private copies of the offline toolchain caches in the sandbox HOME.",
    '# Nothing else is read: the workspace carries the public requirement only.',
    'set -euo pipefail',
    'command -v node >/dev/null 2>&1 || { echo "scaffold: node is not on PATH" >&2; exit 127; }',
    'command -v git >/dev/null 2>&1 || { echo "scaffold: git is not on PATH" >&2; exit 127; }',
    '# The harness passes this script as a native path; normalise backslashes.',
    'script="${0//\\\\//}"',
    'case "$script" in',
    '  */*) here="${script%/*}" ;;',
    '  *) here=. ;;',
    'esac',
    'if command -v cygpath >/dev/null 2>&1; then here="$(cygpath -m "$here")"; fi',
    `exec node "$here/../../tools/scaffold.mjs" ${name} .`,
    '',
  ].join('\n');
}

/** Every generated file, keyed `<case>/<file>`. */
export function generateCases(suite) {
  const out = new Map();
  for (const project of suite.projects) {
    for (const prd of project.prds) {
      out.set(`${prd.manifest.case}/case.yaml`, caseYaml({ project, prd }));
      out.set(`${prd.manifest.case}/scaffold.sh`, scaffoldScript({ prd }));
    }
  }
  return new Map([...out.entries()].sort(([a], [b]) => (a < b ? -1 : 1)));
}

/**
 * Directories under `dir` that hold a case (a case.yaml), generated or not.
 * Anything else there — the eval harness writes its results to
 * `<eval dir>/results/` — is not a case and is left alone.
 */
function caseDirs(dir) {
  if (!existsSync(dir)) return [];
  return readdirSync(dir, { withFileTypes: true })
    .filter((e) => e.isDirectory() && existsSync(join(dir, e.name, 'case.yaml')))
    .map((e) => e.name)
    .sort();
}

/** How `dir` differs from the cases `suite` generates: `<case>/<file>: missing|differs`, `<case>: not generated ...`. */
export function caseDrift(suite, dir) {
  const cases = generateCases(suite);
  const drift = [];
  for (const [rel, body] of cases) {
    const file = join(dir, ...rel.split('/'));
    const current = existsSync(file) ? readFileSync(file, 'utf8') : null;
    if (current !== body) drift.push(`${rel}: ${current === null ? 'missing' : 'differs'}`);
  }
  const expected = new Set([...cases.keys()].map((k) => k.split('/')[0]));
  for (const name of caseDirs(dir)) if (!expected.has(name)) drift.push(`${name}: not generated by the current manifests`);
  return drift;
}

/**
 * Write the generated cases into `dir`. Nothing is ever deleted: a case the
 * manifests no longer generate is reported by caseDrift for removal by hand,
 * and the harness's results beside the cases are never touched.
 */
export function writeCases(suite, dir) {
  const cases = generateCases(suite);
  for (const [rel, body] of cases) {
    const file = join(dir, ...rel.split('/'));
    // What is there is read through one descriptor; a case is replaced whole (rename), never written through a link.
    if (readRegular(file)?.bytes.toString('utf8') === body) continue;
    mkdirSync(join(file, '..'), { recursive: true });
    const tmp = `${file}.${process.pid}.tmp`;
    writeFileSync(tmp, body, { flag: 'wx' });
    renameSync(tmp, file);
    if (rel.endsWith('.sh')) chmodSync(file, 0o755);
  }
  return [...new Set([...cases.keys()].map((k) => k.split('/')[0]))].sort();
}
