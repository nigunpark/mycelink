/**
 * Deterministic generation of the `claude plugin eval` cases.
 *
 * One case per PRD: a prompt both orchestration arms receive byte for byte
 * (the harness's with/without ablation only changes whether the plugin is
 * installed), lightweight structural graders, and a scaffold that builds
 * the workspace from the frozen source. A case carries the public
 * requirement's location and nothing else of the benchmark: no hidden test,
 * reference, mutant, lock, hash or frozen commit. The authoritative verdict
 * is tools/verify-run.mjs, after the run.
 */

import { chmodSync, existsSync, mkdirSync, readFileSync, readdirSync, renameSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { readRegular } from './fsread.mjs';

/** The tools every run may use, in both orchestration arms (plugin eval cases and tools/run-arm.mjs). */
export const ALLOWED_TOOLS = ['Read', 'Glob', 'Grep', 'Write', 'Edit', 'Bash', 'Skill', 'Agent', 'TodoWrite'];

/** Identical in every case and in the multi-module suite; a no-op without the plugin. */
export const MYCELINK_INSTRUCTION = 'If the Mycelink plugin is available, you must use it to coordinate and deliver the work; if it is not available, proceed directly without it.';

const TEST_COMMAND_PATTERN = {
  'maven-junit': 'mvnw[^\\n]*\\btest\\b',
  'pnpm-vitest': '\\bvitest\\b',
  'node-test': 'node[^\\n]*--test',
};

export function casePrompt({ project, prd }) {
  const a = project.adapter;
  const id = prd.manifest.id;
  return [
    `${a.name} needs a change. The requirement ${id} has been approved: \`platform/requirements/${id}.md\`. \`platform/\` is our coordination repository; the code lives in the Git repository \`${a.workspace.repo_dir}/\`. \`README.md\` in this directory lists its modules and the offline build and test commands.`,
    '',
    `Please deliver the requirement end to end: implement every acceptance criterion in the module that owns it, test-first (commit the failing tests before the production code that makes them pass), and keep every existing test passing. Commit everything and leave \`${a.workspace.repo_dir}\` checked out on \`${a.workspace.branch}\` at the commit you are delivering.`,
    '',
    MYCELINK_INSTRUCTION,
    '',
    'Everything builds and tests offline; do not add dependencies. Nobody will be available to answer questions while you work, so make reasonable decisions consistent with the requirement and list them in your final summary. End with a short summary that states which tests you ran with their result, and the commit you delivered.',
  ].join('\n');
}

const q = (s) => `'${String(s).replace(/'/g, "''")}'`;

